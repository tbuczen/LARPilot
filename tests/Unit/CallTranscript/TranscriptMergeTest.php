<?php

declare(strict_types=1);

namespace Tests\Unit\CallTranscript;

use App\Domain\CallTranscript\DTO\SpeakerTranscript;
use App\Domain\CallTranscript\DTO\TranscriptSegment;
use App\Domain\CallTranscript\Service\Transcript\SubtitleParser;
use App\Domain\CallTranscript\Service\Transcript\TranscriptMerger;
use App\Domain\CallTranscript\Service\Transcript\TranscriptTimestamp;
use PHPUnit\Framework\TestCase;
use Tests\Support\CallTranscript\FakeSpeechToTextProvider;

class TranscriptMergeTest extends TestCase
{
    public function testParsesSrtCues(): void
    {
        $segments = (new SubtitleParser())->parse("\xEF\xBB\xBF1\r\n00:12:31,250 --> 00:12:35,000\r\nTo może frakcja\r\nKruków?\r\n\r\n2\r\n01:00:00,000 --> 01:00:01,000\r\nZgoda.\r\n", 'srt');

        $this->assertEquals([
            new TranscriptSegment(751.25, 'To może frakcja Kruków?'),
            new TranscriptSegment(3600.0, 'Zgoda.'),
        ], $segments);
    }

    public function testParsesVttCuesSkippingHeaderNotesAndTags(): void
    {
        $vtt = <<<'VTT'
            WEBVTT
            Kind: captions

            NOTE generated by Craig

            intro
            00:05.000 --> 00:07.000 align:start
            <v anna>Cześć &amp; witajcie</v>

            00:00:09.500 --> 00:00:10.000

            00:00:10.000 --> 00:00:12.000
            Zaczynamy.
            VTT;

        $segments = (new SubtitleParser())->parse($vtt, 'vtt');

        $this->assertEquals([
            new TranscriptSegment(5.0, 'Cześć & witajcie'),
            new TranscriptSegment(10.0, 'Zaczynamy.'),
        ], $segments);
    }

    public function testParsesPlainTextWithOptionalTimestamps(): void
    {
        $segments = (new SubtitleParser())->parse("[00:00:03] Pierwsza\ncontinued line\n\n00:01:00 - Druga", 'txt');

        $this->assertEquals([
            new TranscriptSegment(3.0, 'Pierwsza'),
            new TranscriptSegment(3.0, 'continued line'),
            new TranscriptSegment(60.0, 'Druga'),
        ], $segments);
    }

    public function testMergesSpeakersInTimeOrderWithStableTies(): void
    {
        $parser = new SubtitleParser();
        $anna = $parser->parse("1\n00:00:01,000 --> 00:00:02,000\nHej\n\n2\n00:00:10,000 --> 00:00:11,000\nTak", 'srt');
        $tomekAudio = tempnam(sys_get_temp_dir(), 'tomek_');
        file_put_contents($tomekAudio, "5|Cześć Anna\n10|Też tak myślę");
        $tomek = (new FakeSpeechToTextProvider())->transcribe($tomekAudio, 'pl');
        unlink($tomekAudio);

        $lines = (new TranscriptMerger())->merge([
            new SpeakerTranscript('anna', $anna),
            new SpeakerTranscript('tomek', $tomek),
            new SpeakerTranscript('Note', [new TranscriptSegment(3725.9, 'decision')]),
        ]);

        $this->assertSame([
            '[00:00:01] anna: Hej',
            '[00:00:05] tomek: Cześć Anna',
            '[00:00:10] anna: Tak',
            '[00:00:10] tomek: Też tak myślę',
            '[01:02:05] Note: decision',
        ], $lines);
    }

    public function testConvertsTimestamps(): void
    {
        $this->assertSame(4.5, TranscriptTimestamp::toSeconds('0:00:04.50'));
        $this->assertSame(61.25, TranscriptTimestamp::toSeconds('01:01,25'));
        $this->assertSame('06:00:00', TranscriptTimestamp::format(21600.4));
        $this->assertSame('00:00:00', TranscriptTimestamp::format(-1));
    }
}
